"""Package the team's Skill into the agent (run from the repository root, then deploy):

    python3 -I supabase/package_skill.py

The Edge Function can't open repository files while it runs, so this copies the Skill made
with the BUS4498 Skill Builder (our_team_agent/agent/skills/prepare-clarification-request/)
into skill_bundle.js, word for word, with a SHA-256 of each file. tests/skill.test.js fails
if the copy and the repository files ever differ.
"""
import hashlib, json, pathlib

ROOT = pathlib.Path("our_team_agent/agent/skills/prepare-clarification-request")
FILES = {"SKILL_MD": "SKILL.md", "FIELD_RULES_MD": "references/field-rules.md", "TEMPLATE_MD": "assets/clarification-request-template.md"}

lines = [
    "// GENERATED by package_skill.py from our_team_agent/agent/skills/prepare-clarification-request/.",
    "// Do not edit by hand: change the Skill (BUS4498 Skill Builder), then run",
    "//   python3 -I supabase/package_skill.py",
    "// and deploy. tests/skill.test.js checks this copy matches the repository word for word.",
    'export const SKILL_NAME = "prepare-clarification-request";',
    'export const SKILL_PATH = "our_team_agent/agent/skills/prepare-clarification-request";',
]
digest = hashlib.sha256()
for const, rel in FILES.items():
    text = (ROOT / rel).read_text(encoding="utf-8")
    digest.update(text.encode("utf-8"))
    lines.append(f"export const {const} = {json.dumps(text, ensure_ascii=False)};")
lines.append(f'export const SKILL_SHA256 = "{digest.hexdigest()}";')
pathlib.Path("supabase/functions/agent/skill_bundle.js").write_text("\n".join(lines) + "\n", encoding="utf-8")
print("skill_bundle.js written; SHA-256", digest.hexdigest()[:12])
